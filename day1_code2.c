#include <stdio.h>

int main() {
    int a,b;
    printf("Enter Two Numbers: ");
    scanf("%d%d", &a,&b);

    printf("Sum Of Two Numbers are: %d\n", a+b);
    printf("Difference of two numbers are : %d\n", a-b);
    printf("Product of two numbers are : %d\n", a*b);
    printf("Quotient of two numbers are : %d\n", a/b);
    return 0;

}